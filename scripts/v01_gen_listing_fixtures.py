        "    An aggregator CATEGORY page titled \"190+ Post Doc scholarships\n"
        "    2026-27\". classify_page_intent returns SCHOLARSHIP_DETAIL/0.75\n"
        "    because the page carries deadline and eligibility boilerplate, so it\n"
