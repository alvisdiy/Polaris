HEADER = '''"""Offline fixtures for the two pages that reached the public API in V0.1.

GENERATED by scripts/v01_gen_listing_fixtures.py — do not hand-edit.

Every value below is read from the raw document the V0.1 acquisition run
actually stored for that page, then passed through the production cleaner.
That matters: a hand-written approximation would let these tests pass while the
guard still failed on the real page. Here the fixtures reproduce the *exact*
page-intent verdicts that permitted publication, so a test that asserts the
guard blocks them is really testing the bypass and not a mock of it.

The module is import-time safe — no database, no network. The generator needs a
database; this file does not.

Data is wrapped across lines below purely for line length; the parsed values
are identical to the stored documents.
"""

from __future__ import annotations

FIXTURES: dict[str, dict] = {
'''

FOOTER = '''}


def fixture(name: str) -> dict:
    """Return one fixture by key, failing loudly on a typo."""
    if name not in FIXTURES:
        raise KeyError(
            f"unknown listing fixture {name!r}; have {sorted(FIXTURES)}"
        )
    return FIXTURES[name]
'''


def _literal(value, indent: str = "        ") -> str:
    """Render ``value`` as a wrapped, ruff-clean Python literal.

    The fixture data is long — one aggregator page carries 200 anchor labels —
    so ``repr`` on one line produces lines hundreds of characters wide.

    Returns a bare literal with NO trailing comma: the caller emits the comma,
    because it is the one writing ``'key': <literal>,``.

    Wrapping is done by splitting the *value* and calling ``repr`` on each
    piece, never by splitting a ``repr``. Cutting a repr apart destroys the
    quoting decision it made — Python wraps a string containing an apostrophe
    in double quotes, and splitting that body and re-quoting each half
    single-quoted yields ``'FAQ's'``, which is a syntax error. Adjacent string
    literals concatenate at parse time, so splitting the value is invisible to
    the reader.
    """
    if isinstance(value, list):
        if not value:
            return "[]"
        lines: list[str] = []
        for item in value:
            rendered = _literal(item, indent).splitlines()
            rendered[-1] += ","
            lines.extend(rendered)
        return "[\n" + "\n".join(lines) + f"\n{indent[:-4]}]"

    if not isinstance(value, str) or len(repr(value)) <= 100:
        return f"{indent}{value!r}"

    # Split at the last space inside each window so no word is cut in half.
    # The space is KEPT on the left piece: dropping it silently deletes a
    # character from the value, and the fixture then stops being a faithful
    # copy of the document it came from.
    pieces: list[str] = []
    rest = value
    while len(repr(rest)) > 100:
        cut = rest.rfind(" ", 0, 90)
        if cut <= 0:
            cut = 90
        pieces.append(rest[: cut + 1])
        rest = rest[cut + 1 :]
    pieces.append(rest)
    return "\n".join(f"{indent}{piece!r}" for piece in pieces)


def _block(session, key: str, url: str) -> str:
    row = session.execute(
        text(
            "SELECT document_id, source_id, content_type, raw_content "
            "FROM raw_document WHERE source_url = :url "
            "ORDER BY fetched_at DESC LIMIT 1"
        ),
        {"url": url},
    ).first()
    if row is None:
        raise SystemExit(f"no stored document for {url}; cannot regenerate")

    cleaned = clean(
        LoadedDocument(
            document_id=str(row[0]),
            source_id=str(row[1]),
            source_url=url,
            content_type=row[2],
            raw_content=row[3],
        )
    )
    intent = classify_page_intent(
        url=url,
        page_title=cleaned.page_title,
        headings=cleaned.headings,
        anchors=cleaned.anchors,
        text=cleaned.clean_text,
    )
    guard = classify_listing_page(
        page_title=cleaned.page_title,
        headings=cleaned.headings,
        anchors=cleaned.anchors,
        text=cleaned.clean_text,
        intent=intent,
    )
    print(
        f"{key}: intent={intent.intent}/{intent.confidence} "
        f"guard={guard.verdict} signals={guard.signals}"
    )

    text_blob = " ".join(cleaned.clean_text.split())[:4000]
    note = "\n".join(textwrap.wrap(NOTES[key], width=66, initial_indent="# ",
                                   subsequent_indent="# "))
    return (
        f"    # {note}\n"
        f"    {key!r}: {{\n"
        f"        'url': {url!r},\n"
        f"        'title': {_literal(cleaned.page_title)},\n"
        f"        'headings': {_literal(list(cleaned.headings))},\n"
        f"        'anchors': {_literal(list(cleaned.anchors))},\n"
        f"        'text': {_literal(text_blob)},\n"
        f"        # Measured, not assumed: the verdict this page received at\n"
        f"        # V0.1, and the verdict the guard gives it now.\n"
        f"        'intent_at_v01': {intent.intent!r},\n"
        f"        'intent_confidence_at_v01': {intent.confidence!r},\n"
        f"        'expected_verdict': {guard.verdict!r},\n"
        f"        'expected_signals': {_literal(list(guard.signals))},\n"
        f"        'published_name_in_v01': {PUBLISHED_NAME[key]!r},\n"
        f"    }},\n"
    )


def main() -> None:
    session = SessionLocal()
    try:
        blocks = [_block(session, key, url) for key, url in TARGETS.items()]
    finally:
        session.close()

    target = pathlib.Path("tests/fixtures/listing_pages.py")
    target.write_text(HEADER + "".join(blocks) + FOOTER, encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
