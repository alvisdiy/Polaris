"""Regenerate tests/fixtures/listing_pages.py from the two stored real pages.

The V0.1.1 regression fixtures have to reproduce the *actual* page-intent
verdicts that let these two pages through. Hand-written approximations drift,
so the fixture values are read straight out of the raw documents that the V0.1
acquisition run stored, and the guard is then measured against the same input.

Run from the repo root:

    PYTHONPATH=. .venv/Scripts/python.exe scripts/v01_gen_listing_fixtures.py

Idempotent: it rewrites the same file from the same documents.
"""

